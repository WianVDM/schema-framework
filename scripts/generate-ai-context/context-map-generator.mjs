// NOTE: Auto-generates docs/context-map.md from collected .context.json data.
// NOTE: Replaces the need for manual context-map.md maintenance per .clinerules rules.

import { posix } from 'path'
import { estimateTokens } from './token-budget.mjs'

/**
 * NOTE: Generates docs/context-map.md from all collected context data.
 * Returns { path, tokens } for logging by the orchestrator.
 */
export function generateContextMap(contexts) {
  const layerGroups = { 1: [], 2: [], 3: [] }

  // NOTE: Group contexts by layer for organized output
  for (const { dirPath, context } of contexts) {
    const layer = context.layer
    if (layerGroups[layer]) {
      layerGroups[layer].push({ dirPath, context })
    }
  }

  const lines = [
    '# Context Map',
    '',
    '> NOTE: This file is auto-generated by `scripts/generate-ai-context/`. Do not edit manually.',
    '> Run `pnpm generate-context` to regenerate.',
    '',
    '## Layer Dependency Graph',
    '',
    '```mermaid',
    'graph TD',
    '    L1["Layer 1: Primitives<br/>(packages/core/src/primitives)"]',
    '    L2["Layer 2: Engine<br/>(packages/core/src/engine)"]',
    '    L3["Layer 3: Composition<br/>(apps/showcase/src)"]',
    '    L3 -->|consumes| L2',
    '    L2 -->|consumes| L1',
    '```',
    '',
  ]

  // NOTE: Generate per-layer sections
  const layerNames = { 1: 'Primitives', 2: 'Engine', 3: 'Composition' }
  const layerPaths = {
    1: 'packages/core/src/primitives',
    2: 'packages/core/src/engine',
    3: 'apps/showcase/src',
  }

  for (const [layer, name] of Object.entries(layerNames)) {
    const dirs = layerGroups[layer]
    lines.push(`## Layer ${layer}: ${name}`)
    lines.push('')
    lines.push(`**Root:** \`${layerPaths[layer]}\``)
    lines.push(`**Directories:** ${dirs.length}`)
    lines.push('')

    if (dirs.length > 0) {
      lines.push('```mermaid')
      lines.push('graph TD')
      for (const { dirPath, context } of dirs) {
        const dirId = dirPath.replace(/[/.]/g, '_').replace(/_+/g, '_')
        const purpose = ` — ${sanitizeMermaid(resolvePurpose(context.purpose, 60))}`
        lines.push(`    ${dirId}["${dirPath}${purpose}"]`)
      }
      lines.push('```')
      lines.push('')
    }

    // NOTE: Directory details table
    lines.push('| Directory | Purpose | Files |')
    lines.push('|-----------|---------|-------|')
    for (const { dirPath, context } of dirs) {
      const fileCount = (typeof context.files === 'object' && context.files !== null) ? Object.keys(context.files).length : 0
      const purpose = resolvePurpose(context.purpose, 80)
      const escapedPurpose = purpose.replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ')
      lines.push(`| \`${dirPath}\` | ${escapedPurpose} | ${fileCount} |`)
    }
    lines.push('')
  }

  // NOTE: Cross-layer dependencies section
  lines.push('## Cross-Layer Dependencies')
  lines.push('')
  lines.push('```mermaid')
  lines.push('graph LR')

  // NOTE: Build lookup map for resolving relative deps to known context node IDs
  const dirPathToId = new Map()
  for (const { dirPath } of contexts) {
    const dirId = dirPath.replace(/[/.]/g, '_').replace(/_+/g, '_')
    dirPathToId.set(dirPath.replace(/\\/g, '/'), dirId)
  }

  // NOTE: Deduplicate edges — multiple files in a directory may import from the same target directory
  const seenEdges = new Set()
  for (const { dirPath, context } of contexts) {
    if (!context.extDeps) continue
    const normalizedDir = dirPath.replace(/\\/g, '/')
    const dirId = dirPathToId.get(normalizedDir)
    for (const [file, deps] of Object.entries(context.extDeps)) {
      for (const depEntry of deps) {
        // NOTE: Support both old string format and new { path, confidence } format
        const depPath = typeof depEntry === 'string' ? depEntry : depEntry.path
        if (depPath.startsWith('.')) {
          // NOTE: Resolve relative dep against source directory to find target context
          const depDir = posix.dirname(depPath)
          const resolvedDir = posix.normalize(posix.join(normalizedDir, depDir))
          const targetId = dirPathToId.get(resolvedDir)
          if (targetId && targetId !== dirId) {
            const edgeKey = `${dirId}|imports|${targetId}`
            if (!seenEdges.has(edgeKey)) {
              seenEdges.add(edgeKey)
              lines.push(`    ${dirId} -->|imports| ${targetId}`)
            }
          }
        }
      }
    }
  }
  lines.push('```')
  lines.push('')

  const content = lines.join('\n')

  return { path: 'docs/context-map.md', content, tokens: estimateTokens(content, false) }
}

// NOTE: Truncates a string to maxLen, appending '...' if truncated.
function truncate(str, maxLen) {
  if (str.length <= maxLen) return str
  return str.slice(0, maxLen - 3) + '...'
}

// NOTE: Sanitizes a string for safe use inside Mermaid node label quotes.
function sanitizeMermaid(str) {
  return str
    .replace(/\\/g, '\\\\')   // backslashes first to avoid double-escaping
    .replace(/"/g, '\\"')     // double quotes
    .replace(/]/g, '\\]')     // closing brackets
    .replace(/[\r\n]+/g, ' ') // newlines/carriage returns → spaces
}

// NOTE: Resolves a purpose string, falling back to a clear placeholder when missing or empty.
const MISSING_PURPOSE = 'TODO: describe purpose'
function resolvePurpose(purpose, maxLen) {
  const trimmed = typeof purpose === 'string' ? purpose.trim() : ''
  return trimmed.length > 0 ? truncate(trimmed, maxLen) : truncate(MISSING_PURPOSE, maxLen)
}
